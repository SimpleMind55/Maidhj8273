        b.MouseButton1Click:Connect(function()
            send(w)
            showWords(CurLetter)
        end)
    end
end

-- ───────────── авто-буква из GUI ─────────────
local last = ""

local function tryLetter(l)
    l = string.lower(l or "")
    if l == "" or l == last or not Dict[l] then return end
    last = l
    showWords(l)
    if Mode == "Rage" and RageOn then
        task.delay(RageDelay, function()
            if CurLetter == l then
                local ws = available(l)
                if #ws > 0 then
                    send(ws[math.random(1, #ws)])
                    showWords(l)
                end
            end
        end)
    end
end

local function scan()
    for _, obj in ipairs(PG:GetDescendants()) do
        if (obj:IsA("TextLabel") or obj:IsA("TextButton")) and obj.Visible then
            local t = string.lower(obj.Text or "")
            if #t < 20 and #t > 0 then
                local l = t:match("букв[аы]?[%s:]*([а-яё])")
                       or t:match("на[%s]*([а-яё])[%s]*$")
                       or t:match("^%s*([а-яё])%s*$")
                       or t:match("%[([а-яё])%]")
                       or t:match("letter[%s:]*([a-zа-яё])")
                if l then tryLetter(l) return end
            end
        end
    end
end

task.spawn(function()
    while task.wait(0.45) do pcall(scan) end
end)

