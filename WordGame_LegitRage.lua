    close.Font = Enum.Font.GothamBold
    close.TextSize = 16
    close.MouseButton1Click:Connect(destroyOverlay)

    refreshOverlay()
end

-- ───────────── авто-буква ─────────────
local lastLetter = ""
local function tryLetter(l)
    l = string.lower(l or "")
    if l == "" or not Dict[l] then return end
    if l == lastLetter then return end
    lastLetter = l
    CurLetter = l
    refreshOverlay()
    if RageOn then
        task.delay(RageDelay, function()
            if CurLetter == l then
                local ws = available(l)
                if #ws > 0 then send(ws[math.random(1, #ws)]) end
            end
        end)
    end
end

task.spawn(function()
    while task.wait(0.5) do
        pcall(function()
            for _, obj in ipairs(PG:GetDescendants()) do
                if (obj:IsA("TextLabel") or obj:IsA("TextButton")) and obj.Visible then
                    local t = string.lower(obj.Text or "")
                    if #t > 0 and #t < 24 then
                        local l = t:match("букв[аы]?[%s:]*([а-яё])")
                               or t:match("^%s*([а-яё])%s*$")
                               or t:match("%[([а-яё])%]")
                        if l and Dict[l] then tryLetter(l) return end
                    end
                end
            end
        end)
    end
end)

