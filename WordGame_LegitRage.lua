-- ───────────── Логика ─────────────
local function clearList()
    for _, c in ipairs(list:GetChildren()) do
        if c:IsA("TextButton") then c:Destroy() end
    end
end

local function available(letter)
    letter = string.lower(letter)
    local t = {}
    for _, w in ipairs(Dict[letter] or {}) do
        if not Used[w] then table.insert(t, w) end
    end
    return t
end

local function send(word)
    if not word then return end
    Used[word] = true
    status.Text = "→ " .. word

    -- 1. TextChatService
    pcall(function()
        local ch = TextChatService.TextChannels:FindFirstChild("RBXGeneral")
        if ch then ch:SendAsync(word) end
    end)

    -- 2. Любые RemoteEvent с "word" / "answer" / "say" в имени
    for _, v in ipairs(game:GetDescendants()) do
        if v:IsA("RemoteEvent") then
            local n = v.Name:lower()
            if n:find("word") or n:find("answer") or n:find("say") or n:find("chat") or n:find("message") then
                pcall(function() v:FireServer(word) end)
            end
        end
    end
end

local function show(letter)
    clearList()
    CurLetter = letter
    letL.Text = "Буква: " .. string.upper(letter)
    local words = available(letter)

    if #words == 0 then
        status.Text = "Нет слов"
        return
    end

    for _, w in ipairs(words) do
        local b = Instance.new("TextButton", list)
        b.Size = UDim2.new(1, -6, 0, 24)
        b.BackgroundColor3 = Color3.fromRGB(35, 35, 45)
        b.Text = "  " .. w
        b.TextColor3 = Color3.fromRGB(220,220,230)
        b.Font = Enum.Font.Gotham
        b.TextSize = 13
        b.TextXAlignment = Enum.TextXAlignment.Left
        b.AutoButtonColor = false
        Instance.new("UICorner", b).CornerRadius = UDim.new(0, 5)
        b.MouseButton1Click:Connect(function() send(w) end)
    end
    list.CanvasSize = UDim2.new(0, 0, 0, #words * 27)
end

local function tryRage()
    if Mode ~= "Rage" or not Enabled or CurLetter == "" then return end
    task.delay(RageDelay, function()
        local words = available(CurLetter)
        if #words > 0 then
            send(words[math.random(1, #words)])
        end
    end)
end

-- Детект из чата
local function onMsg(text)
    text = string.lower(text or "")
    local letter = text:match("букв[аы]?[%s:]+([а-яё])")
                 or text:match("на букву%s+([а-яё])")
                 or text:match("слово на%s+([а-яё])")
                 or text:match("ход[%s:]+([а-яё])")

    if letter then
        show(letter)
        status.Text = "Твой ход"
        tryRage()
    end

    for w in text:gmatch("[а-яё]{3,}") do
        Used[w] = true
    end
end

pcall(function()
    TextChatService.MessageReceived:Connect(function(msg)
        if msg.Text then onMsg(msg.Text) end
    end)
end)

pcall(function()
    LP.Chatted:Connect(onMsg)
end)

