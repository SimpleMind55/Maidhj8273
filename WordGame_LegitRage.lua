local Used = {}
local CurLetter = ""
local RageOn = false
local RageDelay = 0.7
local OverlayOpen = false
local overlayGui, overlayPanel, overlayTitle, overlayScroll

local function available(letter)
    letter = string.lower(letter or "")
    local t = {}
    for _, w in ipairs(Dict[letter] or {}) do
        if not Used[w] then table.insert(t, w) end
    end
    return t
end

local function findInput()
    local best
    for _, obj in ipairs(PG:GetDescendants()) do
        if obj:IsA("TextBox") and obj.Visible and obj.AbsoluteSize.X > 30 then
            local n = (obj.Name .. " " .. (obj.PlaceholderText or "")):lower()
            if n:find("word") or n:find("слов") or n:find("answer") or n:find("input") or n:find("guess") or n:find("ответ") or n:find("text") then
                return obj
            end
            best = best or obj
        end
    end
    return best
end

local function send(word)
    if not word or word == "" then return end
    Used[word] = true
    local box = findInput()
    if box then
        box:CaptureFocus()
        task.wait(0.04)
        box.Text = word
        task.wait(0.04)
        pcall(function()
            VIM:SendKeyEvent(true, Enum.KeyCode.Return, false, game)
            task.wait(0.02)
            VIM:SendKeyEvent(false, Enum.KeyCode.Return, false, game)
        end)
        for _, b in ipairs(PG:GetDescendants()) do
            if b:IsA("TextButton") or b:IsA("ImageButton") then
                local t = (b.Name .. " " .. (b.Text or "")):lower()
                if t:find("отправ") or t:find("submit") or t:find("send") or t:find("готово") or t:find("enter") then
                    pcall(function() firesignal(b.MouseButton1Click) end)
                end
            end
        end
    end
    for _, v in ipairs(game:GetDescendants()) do
        if v:IsA("RemoteEvent") then
            local n = v.Name:lower()
            if n:find("word") or n:find("answer") or n:find("submit") or n:find("guess") then
                pcall(function() v:FireServer(word) end)
            end
        end
    end
    refreshOverlay()
end

-- ───────────── полупрозрачное окно со словами ─────────────
local function destroyOverlay()
    if overlayGui then overlayGui:Destroy() end
    overlayGui, overlayPanel, overlayTitle, overlayScroll = nil, nil, nil, nil
    OverlayOpen = false
end

local function refreshOverlay()
    if not overlayScroll then return end
    for _, c in ipairs(overlayScroll:GetChildren()) do
        if c:IsA("TextButton") or (c:IsA("TextLabel") and c.Name == "empty") then c:Destroy() end
    end
    if CurLetter == "" then
        overlayTitle.Text = "🎃  нет буквы"
        return
    end
    overlayTitle.Text = "🎃  " .. string.upper(CurLetter)
    local words = available(CurLetter)
    if #words == 0 then
        local e = Instance.new("TextLabel")
        e.Name = "empty"
        e.Size = UDim2.new(1, 0, 0, 18)
        e.BackgroundTransparency = 1
        e.Text = "нет слов"
        e.TextColor3 = Color3.fromRGB(180, 90, 90)
        e.Font = Enum.Font.Gotham
        e.TextSize = 11
        e.Parent = overlayScroll
        return
    end
    for i, w in ipairs(words) do
        local b = Instance.new("TextButton")
        b.Size = UDim2.new(1, -2, 0, 20)
        b.BackgroundColor3 = Color3.fromRGB(28, 28, 36)
        b.BackgroundTransparency = 0.35
        b.Text = " " .. w
        b.TextColor3 = Color3.fromRGB(220, 220, 230)
        b.Font = Enum.Font.Gotham
        b.TextSize = 11
        b.TextXAlignment = Enum.TextXAlignment.Left
        b.AutoButtonColor = false
        b.LayoutOrder = i
        Instance.new("UICorner", b).CornerRadius = UDim.new(0, 4)
        b.Parent = overlayScroll
        b.MouseButton1Click:Connect(function()
            send(w)
        end)
    end
end

