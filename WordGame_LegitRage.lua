local function available(letter)
    letter = string.lower(letter or "")
    local t = {}
    for _, w in ipairs(Dict[letter] or {}) do
        if not Used[w] then table.insert(t, w) end
    end
    return t
end

-- найти TextBox игры (поле ввода слова)
local function findInput()
    local best = nil
    for _, obj in ipairs(PG:GetDescendants()) do
        if obj:IsA("TextBox") and obj.Visible and obj.AbsoluteSize.X > 40 then
            local n = (obj.Name .. " " .. (obj.PlaceholderText or "")):lower()
            if n:find("word") or n:find("слов") or n:find("answer") or n:find("input") or n:find("text") or n:find("guess") or n:find("ответ") then
                return obj
            end
            best = best or obj
        end
    end
    return best
end

-- отправить слово В ПОЛЕ ИГРЫ, не в чат
local function send(word)
    if not word or word == "" then return end
    Used[word] = true

    local box = findInput()
    if box then
        box:CaptureFocus()
        task.wait(0.05)
        box.Text = word
        task.wait(0.05)
        -- Enter
        pcall(function()
            VIM:SendKeyEvent(true, Enum.KeyCode.Return, false, game)
            task.wait(0.03)
            VIM:SendKeyEvent(false, Enum.KeyCode.Return, false, game)
        end)
        -- на всякий клик по кнопке рядом
        for _, b in ipairs(PG:GetDescendants()) do
            if b:IsA("TextButton") or b:IsA("ImageButton") then
                local t = (b.Name .. " " .. (b.Text or "")):lower()
                if t:find("отправ") or t:find("submit") or t:find("send") or t:find("ok") or t:find("готово") or t:find("enter") then
                    pcall(function()
                        firesignal(b.MouseButton1Click)
                    end)
                end
            end
        end
    end

    -- + remote fallback
    for _, v in ipairs(game:GetDescendants()) do
        if v:IsA("RemoteEvent") then
            local n = v.Name:lower()
            if n:find("word") or n:find("answer") or n:find("submit") or n:find("guess") or n:find("play") then
                pcall(function() v:FireServer(word) end)
            end
        end
    end
end

