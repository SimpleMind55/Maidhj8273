local Used = {}
local CurLetter = ""
local Mode = "Legit"
local RageDelay = 0.8
local AutoEnabled = true

local function available(letter)
    letter = utf8 and letter or string.lower(letter)
    letter = string.lower(letter)
    local t = {}
    for _, w in ipairs(Dict[letter] or {}) do
        if not Used[w] then table.insert(t, w) end
    end
    return t
end

local function send(word)
    if not word or word == "" then return end
    Used[word] = true
    WindUI:Notify({ Title = "Отправлено", Content = word, Duration = 2 })

    -- TextChat
    pcall(function()
        local ch = TextChatService.TextChannels:FindFirstChild("RBXGeneral")
        if ch then ch:SendAsync(word) end
    end)

    -- Fire common remotes
    for _, v in ipairs(game:GetDescendants()) do
        if v:IsA("RemoteEvent") then
            local n = v.Name:lower()
            if n:find("word") or n:find("answer") or n:find("say") or n:find("chat") or n:find("message") or n:find("submit") or n:find("guess") then
                pcall(function() v:FireServer(word) end)
                pcall(function() v:FireServer(LP, word) end)
            end
        end
    end
end

